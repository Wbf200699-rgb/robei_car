#!/usr/bin/env python3
"""Generate server and Android constants from the shared vehicle geometry."""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config" / "vehicle_geometry.json"
PYTHON_OUTPUT = ROOT / "server" / "app" / "vehicle_geometry_generated.py"
JAVA_OUTPUT = (
    ROOT
    / "android"
    / "car_app"
    / "app"
    / "src"
    / "main"
    / "java"
    / "car"
    / "car_app"
    / "geometry"
    / "VehicleGeometry.java"
)


def _load() -> dict[str, object]:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    world = data["world_frame"]
    vehicle = data["vehicle_frame"]
    anchors = world["anchors_m"]
    tags = vehicle["tags"]

    expected_anchors = {"A", "B", "C", "D"}
    if set(anchors) != expected_anchors:
        raise ValueError("geometry must define anchors A, B, C, and D")
    if set(tags) != {"0", "1", "2", "3"}:
        raise ValueError("geometry must define vehicle tags 0, 1, 2, and 3")

    def distance(first: list[float], second: list[float]) -> float:
        return math.dist(first[:2], second[:2])

    if not math.isclose(
        distance(anchors["D"], anchors["B"]), world["rectangle_width_m"], abs_tol=1e-9
    ):
        raise ValueError("anchor D-B distance does not match rectangle width")
    if not math.isclose(
        distance(anchors["B"], anchors["C"]), world["rectangle_height_m"], abs_tol=1e-9
    ):
        raise ValueError("anchor B-C distance does not match rectangle height")

    role_to_tag = {entry["role"]: int(tag_id) for tag_id, entry in tags.items()}
    if set(role_to_tag) != {"front_left", "front_right", "rear_left", "rear_right"}:
        raise ValueError("each vehicle corner role must appear exactly once")
    return data


def _python_text(data: dict[str, object]) -> str:
    world = data["world_frame"]
    vehicle = data["vehicle_frame"]
    validation = data["validation"]
    tags = vehicle["tags"]
    role_to_tag = {entry["role"]: int(tag_id) for tag_id, entry in tags.items()}
    anchors = world["anchors_m"]
    tag_positions = {int(tag_id): entry["position_m"] for tag_id, entry in tags.items()}
    return f'''# Generated by tools/generate_vehicle_geometry.py. Do not edit by hand.\n\nSCHEMA_VERSION = {data["schema_version"]}\nANCHOR_CLOCKWISE_ORDER = ("D", "B", "C", "A")\nANCHORS_M = {anchors!r}\nANCHOR_RECTANGLE_WIDTH_M = {world["rectangle_width_m"]!r}\nANCHOR_RECTANGLE_HEIGHT_M = {world["rectangle_height_m"]!r}\n\nFRONT_LEFT_TAG = {role_to_tag["front_left"]}\nFRONT_RIGHT_TAG = {role_to_tag["front_right"]}\nREAR_LEFT_TAG = {role_to_tag["rear_left"]}\nREAR_RIGHT_TAG = {role_to_tag["rear_right"]}\nTAG_POSITIONS_M = {tag_positions!r}\nVEHICLE_TAG_LENGTH_M = {vehicle["tag_rectangle_length_m"]!r}\nVEHICLE_TAG_WIDTH_M = {vehicle["tag_rectangle_width_m"]!r}\nVEHICLE_DIMENSION_TOLERANCE_M = {validation["vehicle_dimension_tolerance_m"]!r}\nMAXIMUM_FIX_AGE_S = {validation["maximum_fix_age_s"]!r}\nMAXIMUM_FIX_SKEW_S = {validation["maximum_fix_skew_s"]!r}\n\nUWB_EXTERNAL_TRUTH_ONLY = {validation["uwb_is_external_truth_only"]!r}\nPMW3901_POSITION_M = {tuple(vehicle["sensors"]["pmw3901"]["position_m"])!r}\nPMW3901_CENTER_TO_TAIL_M = {vehicle["sensors"]["pmw3901"]["vehicle_center_to_tail_m"]!r}\nVL53L1X_I2C_ADDRESSES_7BIT = {tuple(data["vl53l1x_array"]["i2c_addresses_7bit"])!r}\n'''


def _java_array(values: list[float]) -> str:
    return "{" + ", ".join(f"{value:.10g}" for value in values) + "}"


def _java_text(data: dict[str, object]) -> str:
    world = data["world_frame"]
    vehicle = data["vehicle_frame"]
    validation = data["validation"]
    tags = vehicle["tags"]
    role_to_tag = {entry["role"]: int(tag_id) for tag_id, entry in tags.items()}
    anchors = world["anchors_m"]
    anchor_rows = ",\n            ".join(
        _java_array(anchors[name]) for name in ("A", "B", "C", "D")
    )
    tag_rows = ",\n            ".join(
        _java_array(tags[str(tag_id)]["position_m"]) for tag_id in range(4)
    )
    vl53_addresses = ", ".join(str(value) for value in data["vl53l1x_array"]["i2c_addresses_7bit"])
    return f'''package car.car_app.geometry;\n\n/** Generated from config/vehicle_geometry.json. Do not edit by hand. */\npublic final class VehicleGeometry {{\n    public static final int SCHEMA_VERSION = {data["schema_version"]};\n\n    // Anchor row order is A, B, C, D; world +X is A->C and +Y is A->D.\n    public static final double[][] ANCHORS_M = {{\n            {anchor_rows}\n    }};\n    public static final double ANCHOR_RECTANGLE_WIDTH_M = {world["rectangle_width_m"]};\n    public static final double ANCHOR_RECTANGLE_HEIGHT_M = {world["rectangle_height_m"]};\n\n    public static final int FRONT_LEFT_TAG = {role_to_tag["front_left"]};\n    public static final int FRONT_RIGHT_TAG = {role_to_tag["front_right"]};\n    public static final int REAR_LEFT_TAG = {role_to_tag["rear_left"]};\n    public static final int REAR_RIGHT_TAG = {role_to_tag["rear_right"]};\n\n    // Row index is tag ID. Vehicle +X is forward and +Y is left.\n    public static final double[][] TAG_POSITIONS_M = {{\n            {tag_rows}\n    }};\n    public static final double TAG_RECTANGLE_LENGTH_M = {vehicle["tag_rectangle_length_m"]};\n    public static final double TAG_RECTANGLE_WIDTH_M = {vehicle["tag_rectangle_width_m"]};\n    public static final double DIMENSION_TOLERANCE_M = {validation["vehicle_dimension_tolerance_m"]};\n    public static final double MAXIMUM_FIX_AGE_S = {validation["maximum_fix_age_s"]};\n    public static final double MAXIMUM_FIX_SKEW_S = {validation["maximum_fix_skew_s"]};\n\n    public static final boolean UWB_EXTERNAL_TRUTH_ONLY = true;\n    public static final double[] PMW3901_POSITION_M = {_java_array(vehicle["sensors"]["pmw3901"]["position_m"])};\n    public static final double PMW3901_CENTER_TO_TAIL_M = {vehicle["sensors"]["pmw3901"]["vehicle_center_to_tail_m"]};\n    public static final int[] VL53L1X_I2C_ADDRESSES_7BIT = {{{vl53_addresses}}};\n\n    private VehicleGeometry() {{}}\n}}\n'''


def _write_or_check(path: Path, expected: str, check: bool) -> bool:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == expected:
        return True
    if check:
        print(f"out of date: {path.relative_to(ROOT)}")
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"generated: {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = _load()
    results = [
        _write_or_check(PYTHON_OUTPUT, _python_text(data), args.check),
        _write_or_check(JAVA_OUTPUT, _java_text(data), args.check),
    ]
    return 0 if all(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())

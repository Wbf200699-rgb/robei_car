module obstacle_stop_merge (
  input wire ultrasonic_stop,  // 超声波产生的停车请求。
  input wire lidar_stop,  // 雷达产生的停车请求。
  output wire obstacle_stop  // 合并或当前模块产生的停车请求。
);

  // ===========================================================================
  // 模块行为实现
  // ===========================================================================
  // -----------------------------------------------------------------------------
  // 组合派生信号
  // 以下连续赋值不保存状态，会随输入和寄存器值立即重新计算。
  // -----------------------------------------------------------------------------
  // [ASSIGN] 组合定义“obstacle_stop”：合并或当前模块产生的停车请求。 该组合结果直接由 `ultrasonic_stop`（超声波 / 停车）、`lidar_stop`（激光雷达 / 停车）的当前值决定，不引入时钟周期延迟。
  assign obstacle_stop = ultrasonic_stop | lidar_stop;

endmodule

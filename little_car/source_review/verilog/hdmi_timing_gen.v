// =============================================================================
// 模块: hdmi_timing_gen
// 作用: 生成 1024x600 视频时序、同步信号、数据有效和像素坐标。
// 说明: 水平总周期 1324、垂直总行数 645；有效区外 pixel_x/pixel_y 输出 0。
//
// Robei 源: little_car/model/hdmi_timing_gen.model
// 导出范围: 工程登记模块
// 注意: 本文件是通读副本；工程修改仍应同步回 build/*.v 和对应 .model。
// 重生成: python little_car/source_review/export_sources.py
// =============================================================================

module hdmi_timing_gen (
  input wire clk_pix,  // HDMI 像素时钟域时钟。
  input wire rst_n,  // 低有效复位；0 清零模块内部状态。
  output reg hsync,  // 1024x600 模式水平同步信号；极性和区间由 H_SYNC_START/END 定义。
  output reg vsync,  // 1024x600 模式垂直同步信号；极性和区间由 V_SYNC_START/END 定义。
  output reg v_de,  // 当前像素位于 1024x600 可见区的有效标志。
  output wire [11:0] pixel_x,  // 当前有效显示区水平像素坐标。
  output wire [11:0] pixel_y  // 当前有效显示区垂直像素坐标。
);

  // ===========================================================================
  // 模块行为实现
  // ===========================================================================
  // -----------------------------------------------------------------------------
  // 常量、状态编码与时序参数
  // 这些值决定协议编码、计数周期和状态机含义；修改后必须重新仿真。
  // -----------------------------------------------------------------------------
  parameter H_ACTIVE = 12'd1024, H_FP = 12'd40, H_SYNC = 12'd100, H_BP = 12'd160, H_TOTAL = 12'd1324;  // HDMI 水平时序参数“H / ACTIVE”，单位为像素时钟周期。
  parameter V_ACTIVE = 12'd600,  V_FP = 12'd12, V_SYNC = 12'd10,  V_BP = 12'd23,  V_TOTAL = 12'd645;  // HDMI 垂直时序参数“V / ACTIVE”，单位为行。

  // -----------------------------------------------------------------------------
  // 内部网络、寄存器和计数器
  // wire 只承载组合连接；reg 是过程赋值变量，是否保存跨周期状态由其所在时钟/组合过程决定。
  // 每条声明后的注释继续说明具体数据含义、单位、编码和更新用途。
  // -----------------------------------------------------------------------------
  reg [11:0] h_cnt, v_cnt;  // 同一声明包含两个扫描计数器：h_cnt 是当前行内像素周期位置 0..H_TOTAL-1，v_cnt 是当前帧内行位置 0..V_TOTAL-1。

  // -----------------------------------------------------------------------------
  // [PROCESS] 过程块 1
  // 水平像素计数器，在每行 H_TOTAL-1 后回零。
  // 非阻塞赋值 <= 表示寄存器在该时钟边沿结束后统一更新。
  // -----------------------------------------------------------------------------
  always @(posedge clk_pix or negedge rst_n) begin
      if (!rst_n) h_cnt <= 0;
      else h_cnt <= (h_cnt == H_TOTAL - 1) ? 0 : h_cnt + 1;
  end

  // -----------------------------------------------------------------------------
  // [PROCESS] 过程块 2
  // 垂直行计数器，仅在一行结束时递增。
  // 非阻塞赋值 <= 表示寄存器在该时钟边沿结束后统一更新。
  // -----------------------------------------------------------------------------
  always @(posedge clk_pix or negedge rst_n) begin
      if (!rst_n) v_cnt <= 0;
      else if (h_cnt == H_TOTAL - 1) v_cnt <= (v_cnt == V_TOTAL - 1) ? 0 : v_cnt + 1;
  end

  // -----------------------------------------------------------------------------
  // [PROCESS] 过程块 3
  // 寄存输出同步、数据有效和坐标，避免长组合路径直接进入 TMDS 编码器。
  // 非阻塞赋值 <= 表示寄存器在该时钟边沿结束后统一更新。
  // -----------------------------------------------------------------------------
  always @(posedge clk_pix or negedge rst_n) begin
      if (!rst_n) begin
          hsync <= 1'b0;
          vsync <= 1'b0;
          v_de <= 1'b0;
      end else begin
          hsync <= (h_cnt >= (H_ACTIVE + H_FP)) && (h_cnt < (H_ACTIVE + H_FP + H_SYNC));
          vsync <= (v_cnt >= (V_ACTIVE + V_FP)) && (v_cnt < (V_ACTIVE + V_FP + V_SYNC));
          v_de  <= (h_cnt < H_ACTIVE) && (v_cnt < V_ACTIVE);
      end
  end

  // -----------------------------------------------------------------------------
  // 组合派生信号
  // 以下连续赋值不保存状态，会随输入和寄存器值立即重新计算。
  // -----------------------------------------------------------------------------
  // [ASSIGN] 组合定义“pixel_x”：当前有效显示区水平像素坐标。 该组合结果直接由 `v_de`（V / 数据有效）、`h_cnt`（H / 计数）的当前值决定，不引入时钟周期延迟。
  assign pixel_x = v_de ? h_cnt : 12'd0;
  // [ASSIGN] 组合定义“pixel_y”：当前有效显示区垂直像素坐标。 该组合结果直接由 `v_de`（V / 数据有效）、`v_cnt`（V / 计数）的当前值决定，不引入时钟周期延迟。
  assign pixel_y = v_de ? v_cnt : 12'd0;

endmodule

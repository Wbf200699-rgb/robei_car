  assign motor_forward_ms = 16'd2500;
  // [ASSIGN] 组合定义“motor_turn_ms”：测试/后备配置输出的“电机 / 转向”持续时间，单位 ms。 右侧是固定常量，因此该网络不会随运行状态变化。
  assign motor_turn_ms = 16'd550;
  // [ASSIGN] 组合定义“motor_forward_speed”：“电机 / 前进 / 速度”数值；在 C5 链中为轮速幅值或 11 bit 二补码有符号速度。 右侧是固定常量，因此该网络不会随运行状态变化。
  assign motor_forward_speed = 10'd700;
  // [ASSIGN] 组合定义“motor_turn_speed”：“电机 / 转向 / 速度”数值；在 C5 链中为轮速幅值或 11 bit 二补码有符号速度。 右侧是固定常量，因此该网络不会随运行状态变化。
  assign motor_turn_speed = 10'd650;

endmodule

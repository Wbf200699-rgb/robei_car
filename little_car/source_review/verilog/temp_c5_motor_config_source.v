module temp_c5_motor_config_source (
  output wire motor_enable,  // C5 运动链总使能。
  output wire [15:0] motor_forward_ms,  // 测试/后备配置输出的“电机 / 前进”持续时间，单位 ms。
  output wire [15:0] motor_turn_ms,  // 测试/后备配置输出的“电机 / 转向”持续时间，单位 ms。

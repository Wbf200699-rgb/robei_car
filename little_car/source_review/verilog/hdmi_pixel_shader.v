module hdmi_pixel_shader (
  input wire v_de,  // 旧测试图案发生器的数据有效输入；0 时输出消隐颜色。
  input wire [11:0] pixel_x,  // 当前有效显示区水平像素坐标。
  input wire [11:0] pixel_y,  // 当前有效显示区垂直像素坐标。
  output reg [7:0] r,  // 旧测试图案当前像素的 8 bit 红色分量。
  output reg [7:0] g,  // 旧测试图案当前像素的 8 bit 绿色分量。
  output reg [7:0] b  // 旧测试图案当前像素的 8 bit 蓝色分量。
);

  // ===========================================================================
  // 模块行为实现
  // ===========================================================================
// -----------------------------------------------------------------------------
// [PROCESS] 过程块 1
// 组合过程：根据当前输入和寄存状态计算 r（R）、g（G）、b（B）；过程内应为所有输出路径赋值，避免推断非预期锁存器。
// -----------------------------------------------------------------------------
always @(*) begin
    if (v_de) begin
        if (pixel_x < 12'd341) begin
            r = 8'hFF;
            g = 8'h00;
            b = 8'h00;
        end else if (pixel_x < 12'd682) begin
            r = 8'h00;
            g = 8'hFF;
            b = 8'h00;
        end else begin
            r = 8'h00;
            g = 8'h00;
            b = 8'hFF;
        end
    end else begin
        r = 8'h00;
        g = 8'h00;
        b = 8'h00;
    end
end

endmodule

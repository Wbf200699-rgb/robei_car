module gui_menu_to_state_info (
  input wire [1:0] menu_info,  // 菜单焦点/页面状态编码。
  output reg [4:0] state_info  // 路线 FSM 状态编码。
);

  // ===========================================================================
  // 模块行为实现
  // ===========================================================================
  // -----------------------------------------------------------------------------
  // [PROCESS] 过程块 1
  // 组合过程：根据当前输入和寄存状态计算 state_info（状态 / 信息）；过程内应为所有输出路径赋值，避免推断非预期锁存器。
  // -----------------------------------------------------------------------------
  always @(*) begin
    case (menu_info)
      2'b01: state_info = 5'b00001;
      2'b11: state_info = 5'b00011;
      default: state_info = 5'b00000;
    endcase
  end

endmodule

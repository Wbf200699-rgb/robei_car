// =============================================================================
// 模块: power_on_reset
// 作用: 上电复位延时器，在外部复位释放后继续保持内部复位约 20 ms。
// 说明: POR_CYCLES=1,000,000；50 MHz 下每周期 20 ns，因此延时为 20 ms。
//
// Robei 源: little_car/model/power_on_reset.model
// 导出范围: 工程登记模块
// 注意: 本文件是通读副本；工程修改仍应同步回 build/*.v 和对应 .model。
// 重生成: python little_car/source_review/export_sources.py
// =============================================================================

module power_on_reset (
  input wire clk,  // 50 MHz 系统时钟输入。
  input wire ext_rst_n,  // 板级外部低有效复位输入。
  output reg system_rst_n  // 延时释放后的系统低有效复位。
);

  // ===========================================================================
  // 模块行为实现
  // ===========================================================================
  // -----------------------------------------------------------------------------
  // 常量、状态编码与时序参数
  // 这些值决定协议编码、计数周期和状态机含义；修改后必须重新仿真。
  // -----------------------------------------------------------------------------
  localparam integer POR_CYCLES = 1000000;  // 外部复位释放后继续保持内部复位的周期数。
  // -----------------------------------------------------------------------------
  // 内部网络、寄存器和计数器
  // wire 只承载组合连接；reg 是过程赋值变量，是否保存跨周期状态由其所在时钟/组合过程决定。
  // 每条声明后的注释继续说明具体数据含义、单位、编码和更新用途。
  // -----------------------------------------------------------------------------
  reg [19:0] por_count;  // 外部 rst_n 释放后累计的 50 MHz 周期数；计满 POR_CYCLES=1,000,000 后才把 system_rst_n 置高。

  // -----------------------------------------------------------------------------
  // [INITIAL] 初始化块 1
  // 为支持 FPGA 上电即进入确定复位状态，初始化 por_count=0、system_rst_n=0；外部复位时序过程随后接管。
  // 该块不重复执行；后续状态变化由 always 过程负责。
  // -----------------------------------------------------------------------------
  initial begin
    por_count = 20'd0;
    system_rst_n = 1'b0;
  end

  // -----------------------------------------------------------------------------
  // [PROCESS] 过程块 1
  // 上电/复位计数器：外部复位立即拉低，计满后只释放一次。
  // 非阻塞赋值 <= 表示寄存器在该时钟边沿结束后统一更新。
  // -----------------------------------------------------------------------------
  always @(posedge clk or negedge ext_rst_n) begin
    if (!ext_rst_n) begin
      por_count <= 20'd0;
      system_rst_n <= 1'b0;
    end else if (!system_rst_n) begin
      if (por_count >= POR_CYCLES - 1) begin
        por_count <= por_count;
        system_rst_n <= 1'b1;
      end else begin
        por_count <= por_count + 20'd1;
      end
    end
  end

endmodule

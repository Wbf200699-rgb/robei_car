module hdmi_const (
  output wire [9:0] tmds_clk_pattern,  // TMDS 时钟通道固定 10 bit 码型 1111100000。
  output wire gnd_bit  // HDMI 辅助连接使用的固定逻辑 0。
);

  // ===========================================================================
  // 模块行为实现
  // ===========================================================================
// -----------------------------------------------------------------------------
// 组合派生信号
// 以下连续赋值不保存状态，会随输入和寄存器值立即重新计算。
// -----------------------------------------------------------------------------
// [ASSIGN] 组合定义“tmds_clk_pattern”：TMDS 时钟通道固定 10 bit 码型 1111100000。 右侧是固定常量，因此该网络不会随运行状态变化。
assign tmds_clk_pattern = 10'b1111100000;
// [ASSIGN] 组合定义“gnd_bit”：HDMI 辅助连接使用的固定逻辑 0。 右侧是固定常量，因此该网络不会随运行状态变化。
assign gnd_bit = 1'b0;

endmodule

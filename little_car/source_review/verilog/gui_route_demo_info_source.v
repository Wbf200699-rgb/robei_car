module gui_route_demo_info_source (
  output wire [1:0] system_info,  // GUI 演示使用的固定 2 bit 系统状态，不进入实际小车主链。
  output wire [63:0] route_info  // 64 bit 路线命令队列；最低 2 bit 是下一条命令。
);

  // ===========================================================================
  // 模块行为实现
  // ===========================================================================
  // -----------------------------------------------------------------------------
  // 组合派生信号
  // 以下连续赋值不保存状态，会随输入和寄存器值立即重新计算。
  // -----------------------------------------------------------------------------
  // [ASSIGN] 组合定义“system_info”：GUI 演示使用的固定 2 bit 系统状态，不进入实际小车主链。 右侧是固定常量，因此该网络不会随运行状态变化。
  assign system_info = 2'b01;

  // Low bits are earlier steps:
  // 11 forward, 01 right, 10 left, 00 stop.
  // [ASSIGN] 组合定义“route_info”：64 bit 路线命令队列；最低 2 bit 是下一条命令。 右侧是固定常量，因此该网络不会随运行状态变化。
  assign route_info = {
    40'd0,
    2'b11, 2'b10, 2'b11, 2'b01,
    2'b11, 2'b01, 2'b11, 2'b10,
    2'b11, 2'b01, 2'b11, 2'b11
  };

endmodule
